#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────────────────────────
# SMART Buddy twin — assemble this repository's .env (what compose and `npm run dev` both read: the
# smartbuddy-frontend build args and runtime settings) and .env.development.local (Vite reads it after
# .env in dev mode only; it switches the login off). Both are gitignored, and .dockerignore keeps both
# out of the image. It generates NO secrets and carries no
# backend credential: the Postgres password and the chat's broker login live in backend/.env
# (backend/bootstrap-env.sh).
#
# The chat asks the backend's chat route (central-specs decision 0007), so the twin holds NO broker value
# any more: no VITE_SOLACE_* and no VITE_SAM_TOPIC_*. Moving off them is ordered: backend/bootstrap-env.sh
# copies them from this repository's .env into backend/.env once. If this .env still holds them and
# backend/.env (SB_BACKEND_ENV, default ../backend/.env) has no SB_SAM_SOLACE_URL yet, this script stops
# and says so, so the values are never dropped before they are copied.
# The login (STYL CIAM realm `demo`, client `demo-application`; central-specs decision 0003) is switched
# on for the docker build and off for `npm run dev` (the dev server has no token proxy). Its client
# secret, KEYCLOAK_CLIENT_SECRET, is a RUNTIME setting of the frontend container — never a build arg,
# never in .env.development.local; Vite exposes only VITE_* keys, so `npm run dev` never bundles it — resolved from the environment, then an existing twin/.env; with neither it
# is left empty and marked MISSING (fill it in by hand; the login then fails until it is set).
# No value is printed — only a checklist naming where each came from.
#
#   cd /data/sb-helper/twin && ./bootstrap-env.sh
#   # then review .env and build: docker compose up -d --build   (see DEPLOY.md)
# ─────────────────────────────────────────────────────────────────────────────────────────────────
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$REPO_DIR/.env"
BACKEND_ENV="${SB_BACKEND_ENV:-$REPO_DIR/../backend/.env}"

# grab KEY FILE  → the value of KEY=… (last assignment wins; strips surrounding quotes + CR)
grab() {
  local key="$1" file="$2"
  [ -f "$file" ] || return 0
  sed -n "s/^[[:space:]]*${key}=//p" "$file" | tail -n1 \
    | sed -e 's/\r$//' -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'\$/\1/"
}

# ── the broker values leave this repository only after the backend has them (decision 0007) ───────
DROPPED=""
if [ -n "$(grab VITE_SOLACE_URL "$OUT")" ]; then
  if [ -z "$(grab SB_SAM_SOLACE_URL "$BACKEND_ENV")" ]; then
    echo "stop: .env still holds the chat's broker values (VITE_SOLACE_*) and $BACKEND_ENV has no SB_SAM_SOLACE_URL." >&2
    echo "      Run backend/bootstrap-env.sh first — it copies them into backend/.env — then run this again." >&2
    exit 1
  fi
  DROPPED="yes"
fi

# ── the login's client secret (runtime only): environment → existing twin/.env → MISSING ──────────
KC_SECRET="${KEYCLOAK_CLIENT_SECRET:-}"
if [ -n "$KC_SECRET" ]; then KC_SRC="SET (from environment)"
else
  KC_SECRET="$(grab KEYCLOAK_CLIENT_SECRET "$OUT")"
  if [ -n "$KC_SECRET" ]; then KC_SRC="SET (preserved, twin .env)"
  else KC_SRC="MISSING — fill in by hand (the demo-application client's secret; see DEPLOY.md §4)"; fi
fi

if [ -f "$OUT" ]; then
  cp "$OUT" "$OUT.bak.$(date +%s)"
  echo "note: existing .env backed up; its client secret is preserved (see checklist)."
fi

umask 177   # .env → 600
cat > "$OUT" <<EOF
# SMART Buddy twin .env — generated by bootstrap-env.sh. DO NOT COMMIT. Re-run bootstrap-env.sh to refresh.
# Frontend build args, plus the login's client secret (a runtime setting of the frontend container).
# No backend credential lives here (those are in backend/.env), and no broker value: the chat asks the
# backend's chat route (central-specs decision 0007).

SB_FRONTEND_PORT=8097
VITE_SB_API_URL=/smartbuddy-api
# Login: STYL CIAM realm "demo", confidential client "demo-application" (central-specs decision 0003)
VITE_KEYCLOAK_ENABLED=true
VITE_KEYCLOAK_OIDC_CONFIG_URL=https://ciam-uat.styl.solutions/realms/demo/.well-known/openid-configuration
VITE_KEYCLOAK_CLIENT_ID=demo-application
VITE_KEYCLOAK_TOKEN_PROXY=auth/token
# Runtime only (the container's /auth/token proxy adds it; never a build arg, never in the bundle)
KEYCLOAK_TOKEN_ENDPOINT=https://ciam-uat.styl.solutions/realms/demo/protocol/openid-connect/token
KEYCLOAK_CLIENT_SECRET=$KC_SECRET

# shared docker network (override only if the platform compose project name differs)
BACKEND_NETWORK=solace-pubsub-geo-filtering_backend
EOF

# ── .env.development.local: what `npm run dev` changes on top of .env (Vite, dev mode only) ─────────
cat > "$REPO_DIR/.env.development.local" <<EOF
# SMART Buddy — local dev overrides on top of .env. Generated by bootstrap-env.sh. DO NOT COMMIT.
# No login under the dev server: it has no /auth/token proxy for the confidential client
VITE_KEYCLOAK_ENABLED=false
EOF

echo "wrote $OUT + .env.development.local (chmod 600). Values (none shown):"
echo "  ✓ VITE_KEYCLOAK_*       — CIAM realm demo, client demo-application (login on; off for npm run dev)"
[ "${KC_SRC%% *}" = MISSING ] && mark="✗" || mark="✓"
echo "  $mark KEYCLOAK_CLIENT_SECRET — $KC_SRC"
[ -n "$DROPPED" ] && echo "  note: the chat's broker values (VITE_SOLACE_*, VITE_SAM_TOPIC_*) were dropped from .env — backend/.env holds them now; the old file is in .env.bak.*"
[ -f "$REPO_DIR/client/.env" ] && echo "  note: client/.env is left over from before the flatten and unused — remove the client/ folder (rm -rf client)."
echo
echo "Next: docker compose up -d --build (see DEPLOY.md). Backend env: backend/bootstrap-env.sh."
